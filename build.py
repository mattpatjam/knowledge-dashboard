#!/usr/bin/env python3
"""Build data.js for the knowledge dashboard.

Reads categories.json (source of truth for the 12 categories), walks
.claude/knowledge/books/<slug>/*.md, parses each book's framework reference
markdown into sections, and emits data.js as a classic script defining two
globals: CATEGORIES and BOOKS_DATA. No JSON is fetched at runtime — the
dashboard loads everything via a plain <script src="data.js"> tag so it
works over file://.

Deterministic: categories iterate in categories.json order, files sort
alphabetically within each category directory.
"""

import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
BOOKS_ROOT = os.path.join(SCRIPT_DIR, "books")
CATEGORIES_PATH = os.path.join(SCRIPT_DIR, "categories.json")
OUTPUT_PATH = os.path.join(SCRIPT_DIR, "data.js")

H1_RE = re.compile(r"^# (.+)$", re.MULTILINE)
CITATION_RE = re.compile(r'^\*Book:\s*[“"](.+?)[”"]\s*[—-]+\s*(.+?)\*\s*$', re.MULTILINE)
SECTION_HEADING_RE = re.compile(r"^## \d+\. (.+)$")


def warn(filename, reason):
    print(f"WARNING: skipping {filename}: {reason}", file=sys.stderr)


def parse_book(path, rel_path):
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()

    h1_match = H1_RE.search(text)
    if not h1_match:
        warn(rel_path, "no H1 title line found")
        return None

    h1_title = h1_match.group(1).strip()
    # Strip " — Framework Reference" suffix (em dash or hyphen variants)
    h1_title = re.sub(r"\s*[—-]+\s*Framework Reference\s*$", "", h1_title).strip()

    citation_match = CITATION_RE.search(text)
    if citation_match:
        title = citation_match.group(1).strip()
        author = citation_match.group(2).strip()
    else:
        title = h1_title
        author = ""

    # Split on lines that are exactly "---" (nothing else on the line).
    chunks = re.split(r"^---$", text, flags=re.MULTILINE)

    sections = []
    for chunk in chunks:
        lines = chunk.split("\n")
        heading = None
        heading_idx = None
        for i, line in enumerate(lines):
            m = SECTION_HEADING_RE.match(line)
            if m:
                heading = m.group(1).strip()
                heading_idx = i
                break
        if heading is None:
            # Preamble / disclaimer chunk, or a chunk without a numbered
            # section heading — not a section.
            continue
        content = "\n".join(lines[heading_idx + 1:]).strip()
        sections.append({"heading": heading, "content": content})

    if not sections:
        warn(rel_path, "no valid numbered sections (## N. Heading) found")
        return None

    return {
        "title": title,
        "author": author,
        "sourceFile": rel_path,
        "sections": sections,
    }


def main():
    with open(CATEGORIES_PATH, "r", encoding="utf-8") as f:
        categories = json.load(f)

    books = []
    per_category_counts = {}

    for cat in categories:
        slug = cat["slug"]
        display_name = cat["displayName"]
        per_category_counts[slug] = 0
        cat_dir = os.path.join(BOOKS_ROOT, slug)
        if not os.path.isdir(cat_dir):
            continue  # No content yet — expected, skip silently.
        filenames = sorted(
            fn for fn in os.listdir(cat_dir)
            if fn.endswith(".md") and os.path.isfile(os.path.join(cat_dir, fn))
        )
        for fn in filenames:
            path = os.path.join(cat_dir, fn)
            rel_path = os.path.relpath(path, BOOKS_ROOT)
            book = parse_book(path, rel_path)
            if book is None:
                continue
            book_entry = {
                "category": slug,
                "categoryDisplayName": display_name,
                "title": book["title"],
                "author": book["author"],
                "sourceFile": book["sourceFile"],
                "sections": book["sections"],
            }
            books.append(book_entry)
            per_category_counts[slug] += 1

    categories_out = [
        {
            "slug": cat["slug"],
            "displayName": cat["displayName"],
            "driveFolderName": cat["driveFolderName"],
            "bookCount": per_category_counts[cat["slug"]],
        }
        for cat in categories
    ]

    total_sections = sum(len(b["sections"]) for b in books)

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py — do not edit by hand.\n")
        f.write("// Classic script (no modules): loaded via <script src=\"data.js\">.\n")
        f.write("const CATEGORIES = ")
        f.write(json.dumps(categories_out, ensure_ascii=False, indent=2))
        f.write(";\n\n")
        f.write("const BOOKS_DATA = ")
        f.write(json.dumps(books, ensure_ascii=False, indent=2))
        f.write(";\n")

    print(f"Wrote {OUTPUT_PATH}")
    print(f"Total books indexed: {len(books)}")
    print(f"Total sections: {total_sections}")
    print("Per-category counts:")
    for cat in categories:
        print(f"  {cat['slug']}: {per_category_counts[cat['slug']]}")


if __name__ == "__main__":
    main()
